/**
 * GitOps: desired-state JSON in the installer's Git repo.
 * Sync upserts records; drift compares desired JSON to Terraform state/live.
 */

export type GitOpsSyncStatus = 'idle' | 'syncing' | 'error' | 'ok';

export interface GitOpsSettings {
  /**
   * HTTPS or SSH clone URL of the intent repo (any Git host).
   * Prefer a clean URL without userinfo — store tokens via GitOpsSecrets.
   */
  repoUrl: string;
  branch: string;
  /**
   * Optional path prefix inside the repo (empty = repo root).
   * Layout: <cloud>/<env>/<type>/<name>.json plus archive/.
   */
  pathPrefix: string;
  /** Poll interval in seconds (0 = manual sync only) */
  syncIntervalSec: number;
  enabled: boolean;
  updatedAt: string;
  /**
   * API-only: true when a token is stored for HTTPS private remotes.
   * Never includes the secret itself.
   */
  authConfigured?: boolean;
  /**
   * API-only: ISO date (YYYY-MM-DD) when the stored host token expires.
   * Safe to expose — not a secret. Operators set this when pasting a PAT.
   */
  authExpiresAt?: string;
}

/**
 * HTTPS credentials for private remotes (any Git provider).
 * Stored under GRID_DATA_DIR/gitops-secrets.json — token never returned by the API.
 * Grid does not mint these tokens. Create a personal access token, deploy token,
 * or app password on the Git host and paste it here.
 */
export interface GitOpsSecrets {
  /**
   * Git username for HTTPS basic auth.
   * Default at sync time is `git` when omitted (works with most PAT flows).
   * Override per host when needed (e.g. GitLab `oauth2`, Bitbucket `x-token-auth`).
   */
  username?: string;
  /** Host-issued PAT / deploy token / app password (not generated by Grid) */
  token: string;
  /**
   * When the host token stops working (operator-declared).
   * ISO calendar date `YYYY-MM-DD` or full ISO timestamp.
   */
  tokenExpiresAt?: string;
  updatedAt: string;
}

export interface GitOpsRuntimeStatus {
  settings: GitOpsSettings | null;
  syncStatus: GitOpsSyncStatus;
  lastSyncAt?: string;
  lastSyncError?: string;
  lastCommit?: string;
  lastCommitMessage?: string;
  clonePath?: string;
  trackedCount: number;
}

export type DriftKind =
  | 'in_sync'
  | 'desired_ahead'
  | 'live_drift'
  | 'unknown'
  | 'no_state';

export interface DriftReport {
  infrastructureId: string;
  kind: DriftKind;
  /** True when terraform plan reports changes (desired ≠ state/live) */
  hasDrift: boolean;
  /** True when synced Git content differs from last-applied hash */
  gitChangedSinceApply: boolean;
  summary: string;
  /** Human lines from terraform plan / state */
  changes: string[];
  planExcerpt?: string;
  /** Operator guidance */
  actions: {
    /** Make live match Git desired state */
    applyGitDesired: string;
    /** Keep live; update Git JSON by hand */
    updateGitToMatchLive: string;
  };
  checkedAt: string;
}

export interface GitOpsFileRecord {
  /** Relative path in repo, e.g. aws/development/vpc/demo-vpc.json */
  gitPath: string;
  contentHash: string;
  commit?: string;
}
