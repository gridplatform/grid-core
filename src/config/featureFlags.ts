/**
 * Grid feature flags — edit THIS file (not .env) to turn features on or off.
 *
 * Keep in sync with: grid-ui/src/config/featureFlags.ts
 * (UI and API each have a copy; change both or the console will offer deploys
 * the API rejects.)
 *
 * ─────────────────────────────────────────────────────────────────────────
 * HOW TO TURN A DEPLOY ON (after you verified it works)
 * ─────────────────────────────────────────────────────────────────────────
 *
 * Deploy flags are provider × resource type. Example: Azure VM.
 *
 * Find that provider under `deployFlags` below and flip the line from false
 * to true (sync both grid-core and grid-ui copies). Example:
 *
 *   "vm": true,  // was false
 *
 * Restart grid-core (and Vite for the UI copy) after you save.
 *
 * Product pages (Topology, APM, …) use `productFlags` at the top — set true/false
 * there the same way.
 *
 * Defaults today: all AWS + GCP types on; every other provider off.
 * Kubernetes workload kinds (CronJob, Helm, …) are not gated here yet.
 *
 * Provider keys are always quoted strings (e.g. "aws", "deutsche-telekom") so
 * hyphenated ids look the same as the rest. The id must match the Terraform
 * bank folder name (deutsche-telekom/, not deutscheTelekom).
 *
 * Resource types under each provider are listed explicitly (alphabetical).
 * Keys mirror grid-cli resourceCatalog.ts plus deploy aliases.
 */

export type ProductFlagKey =
  | 'deployments'
  | 'infrastructure'
  | 'releases'
  | 'monitoring'
  | 'alerts'
  | 'apm'
  | 'logging'
  | 'topology'
  | 'admin';

export const productFlags: Record<ProductFlagKey, boolean> = {
  deployments: true,
  infrastructure: true,
  releases: true,
  monitoring: false,
  alerts: false,
  apm: false,
  logging: false,
  topology: false,
  admin: true,
};

export function isProductEnabled(key: ProductFlagKey): boolean {
  return productFlags[key] === true;
}

/** Collapse provider spellings the console and CLI both accept onto one id. */
export function normalizeProviderId(raw?: string): string {
  const p = (raw || 'aws').trim().toLowerCase();
  if (p === 'amazon' || p === 'amazon web services') return 'aws';
  if (p === 'google' || p === 'google cloud' || p === 'gcloud') return 'gcp';
  if (p === 'microsoft' || p === 'microsoft azure') return 'azure';
  if (p === 'oci' || p === 'oracle cloud') return 'oracle';
  if (p === 'ibm cloud') return 'ibm';
  if (p === 'aliyun') return 'alibaba';
  if (p === 'dt' || p === 'open telekom cloud' || p === 'otc') return 'deutsche-telekom';
  if (p === 'ctrl-s' || p === 'ctrls cloud') return 'ctrls';
  if (p === 'red hat openshift' || p === 'rosa') return 'openshift';
  return p;
}

